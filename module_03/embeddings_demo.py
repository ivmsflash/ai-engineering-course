"""
Модуль 3, Занятие 5 (часть В) — эмбеддинги и семантическая близость.

Эмбеддинг — это перевод текста в вектор чисел. Два текста об одном и том же
дают близкие векторы, даже если в них нет ни одного общего слова. Именно на этом
стоит семантический поиск, а на нём — весь RAG в Модуле 4.

Здесь мы проверяем главное: РАБОТАЕТ ли это на русском промышленном тексте.
Ответ не очевиден, и цифры ты получишь сам.

ТВОЯ РАБОТА: TODO 1-3. Кода не пишешь — меняешь наборы фраз и смотришь на числа.

Запуск (из папки module_03):
    python embeddings_demo.py

Первый запуск скачивает модели (~560 МБ суммарно) — это займёт несколько минут.
Дальше они берутся из кэша.
"""

from sentence_transformers import SentenceTransformer, util

# Две модели: англоязычная и многоязычная. Обе локальные, обе работают без GPU.
MODEL_EN = "all-MiniLM-L6-v2"                        # ~90 МБ, обучена на английском
MODEL_MULTI = "paraphrase-multilingual-MiniLM-L12-v2"  # ~470 МБ, знает русский


# ====================================================================
#  НАСТРОЙКИ СТУДЕНТА
# ====================================================================

# TODO 1: пары фраз, которые ПО СМЫСЛУ означают одно и то же, но написаны
# разными словами. Так и бывает в жизни: в регламенте одно слово, в заявке
# оператора — другое.
# Замени ___ на свои пары из области ПромТеха. Нужно минимум 3 пары.
BLIZKIE_PARY = [
    ("Конвейер КМ-101 остановился, лента буксует",
     "Транспортёрная лента встала из-за пробуксовки"),

    ("С какой периодичностью проводить ТО компрессора?",
     "Регламент технического обслуживания компрессорной установки"),

    ("___", "___"),
]

# TODO 2: пары фраз, которые НЕ связаны по смыслу И не имеют общих слов.
# Модель обязана развести их уверенно. Замени ___ на свою пару.
DALEKIE_PARY = [
    ("Прошу выдать доступ к системе учёта заявок",
     "Насос НМ-205 подтекает, нужен ремонт"),

    ("Конвейер КМ-101 остановился",
     "Как оформить отпуск в отделе кадров"),

    ("___", "___"),
]

# TODO 3: ЛОЖНЫЕ СОВПАДЕНИЯ — самое интересное в этом задании.
# Пары, где есть ОБЩИЕ СЛОВА, но смысл совершенно разный. Модель смотрит на слова
# и легко попадается. Именно так семантический поиск достаёт не тот документ.
#
# Придумай минимум одну свою пару. Подсказки, где искать:
#   «давление» — в гидросистеме и в коллективе
#   «лента»    — конвейерная и измерительная
#   «пуск»     — оборудования и производственной линии
#
# Эти пары НЕ входят в расчёт зазора: это не ошибка модели, а её предел.
LOVUSHKI = [
    ("Высокое давление в гидросистеме пресса П-7",
     "Высокое давление в коллективе и текучка кадров"),

    ("___", "___"),
]


# ====================================================================
#  КОД НИЖЕ УЖЕ РАБОТАЕТ — менять не нужно, но прочитай
# ====================================================================

def similarity(model, a: str, b: str) -> float:
    """Косинусная близость двух фраз: 1.0 — идентичны по смыслу, 0.0 — не связаны."""
    emb = model.encode([a, b])
    return float(util.cos_sim(emb[0], emb[1])[0][0])


def check_model(name: str):
    """Прогоняет обе группы пар через модель и считает ЗАЗОР."""
    print()
    print("=" * 84)
    print(f"МОДЕЛЬ: {name}")
    print("=" * 84)

    model = SentenceTransformer(name)

    print("\n  Пары, которые ДОЛЖНЫ быть близки:")
    close = []
    for a, b in BLIZKIE_PARY:
        score = similarity(model, a, b)
        close.append(score)
        print(f"    {score:5.3f}   {a[:34]:<34} <-> {b[:34]}")

    print("\n  Пары, которые ДОЛЖНЫ быть далеки:")
    far = []
    for a, b in DALEKIE_PARY:
        score = similarity(model, a, b)
        far.append(score)
        print(f"    {score:5.3f}   {a[:34]:<34} <-> {b[:34]}")

    gap = min(close) - max(far)
    print(f"\n  Худшая близкая пара : {min(close):.3f}")
    print(f"  Лучшая далёкая пара : {max(far):.3f}")
    print(f"  ЗАЗОР               : {gap:+.3f}")

    if gap <= 0:
        print("  ВЕРДИКТ: модель НЕ отделяет смысл от шума. Поиск на ней работать не будет.")
    elif gap < 0.15:
        print("  ВЕРДИКТ: модель различает смысл, но запас маленький. Будет путаться.")
    else:
        print("  ВЕРДИКТ: модель уверенно различает смысл. На такой можно строить поиск.")

    # Ловушки считаем отдельно: это не «ошибка модели», а граница метода.
    print("\n  Ложные совпадения (общие слова, разный смысл):")
    for a, b in LOVUSHKI:
        score = similarity(model, a, b)
        alarm = "  <- модель попалась" if score >= min(close) else ""
        print(f"    {score:5.3f}   {a[:34]:<34} <-> {b[:34]}{alarm}")

    return gap


def main():
    if any("___" in p for pair in BLIZKIE_PARY + DALEKIE_PARY + LOVUSHKI for p in pair):
        print("Сначала заполни свои пары фраз (TODO 1-3) — там остались ___.")
        return

    gap_en = check_model(MODEL_EN)
    gap_multi = check_model(MODEL_MULTI)

    print()
    print("=" * 84)
    print("ИТОГ")
    print("=" * 84)
    print(f"  {MODEL_EN:<40} зазор {gap_en:+.3f}")
    print(f"  {MODEL_MULTI:<40} зазор {gap_multi:+.3f}")
    print()
    print("  Обе модели одного размера и обе работают локально без GPU.")
    print("  Разница только в том, на каких языках их обучали.")
    print()
    print("  Ложные совпадения ловятся ОБЕИМИ моделями: общие слова обманывают")
    print("  даже хорошую модель. Это предел метода, а не дефект конкретной модели.")


if __name__ == "__main__":
    main()
